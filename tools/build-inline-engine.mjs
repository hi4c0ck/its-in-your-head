#!/usr/bin/env node
// tools/build-inline-engine.mjs
//
// Regenerates the inline portrait-engine block inside desktop/plugin.js
// from the source-of-truth desktop/portrait-engine.mjs, keeping the
// single-file plugin runtime self-contained (Hermes loads one ESM file).
//
// Usage:  node tools/build-inline-engine.mjs
// Output: writes plugin.js in place; verifies that everything outside the
// marker lines is byte-identical to the previous file; prints the engine
// block sha256 (same value the tuner builder prints) so a stale HTML
// tuner is detectable.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MJS = path.join(root, 'desktop', 'portrait-engine.mjs');
const PLUGIN = path.join(root, 'desktop', 'plugin.js');
const START = '// IYH-PORTRAIT-ENGINE-START';
const END = '// IYH-PORTRAIT-ENGINE-END';

const INLINE_BANNER = [
  '/*',
  " * Inline portrait engine for Hermes Desktop's single-file plugin loader.",
  ' * Generated by build-inline-engine.mjs from portrait-engine.mjs.',
  ' * Do not edit this copy independently.',
  ' */',
].join('\n');

// ---- read the source of truth (normalize line endings for processing) ----
const mjsRaw = readFileSync(MJS, 'utf8');
const mjs = mjsRaw.replace(/\r\n/g, '\n');

// The .mjs header is leading `//` comment lines; strip it for the inline
// copy (the inline banner replaces it) and drop the module `export` so the
// block stays plain module-scope `const` like the original loader expects.
const mjsLines = mjs.split('\n');
const bodyStartLine = mjsLines.findIndex((l) => l.startsWith('export const IYH_PORTRAIT'));
let body = mjsLines.slice(bodyStartLine >= 0 ? bodyStartLine : 0).join('\n');
while (body.endsWith('\n')) body = body.slice(0, -1); // drop file-trailing newlines
if (!body.startsWith('export const IYH_PORTRAIT')) {
  throw new Error('portrait-engine.mjs must start with `export const IYH_PORTRAIT` (after header comments)');
}
body = body.slice('export '.length); // plain module-scope `const` for the inline block

// ---- splice into plugin.js, preserving everything else byte-for-byte ----
const pluginRaw = readFileSync(PLUGIN, 'utf8');
const plugin = pluginRaw.replace(/\r\n/g, '\n');
const mS = plugin.indexOf('\n' + START); // includes the newline before the marker line
const mE = plugin.indexOf('\n' + END);
if (mS < 0 || mE < 0 || mE <= mS) throw new Error('engine markers not found in plugin.js');
const before = plugin.slice(0, mS + 1); // through the newline, NOT the marker line
const after = plugin.slice(mE + 1);    // from the END marker text onward
const nextBlock = START + '\n' + INLINE_BANNER + '\n' + body + '\n';
if (before + nextBlock + after === plugin) {
  console.log('plugin.js engine block already up to date; nothing to write');
} else {
  // Detect the file's native line endings and restore them.
  const crlf = pluginRaw.includes('\r\n');
  const out = before + nextBlock + after;
  writeFileSync(PLUGIN, crlf ? out.replace(/\n/g, '\r\n') : out);
  console.log('wrote desktop/plugin.js with regenerated engine block');
}

// Verify the splice: outside the markers, nothing may have moved.
const check = readFileSync(PLUGIN, 'utf8').replace(/\r\n/g, '\n');
const cS = check.indexOf('\n' + START);
const cE = check.indexOf('\n' + END);
if (cS < 0 || cE < 0 || check.slice(0, cS + 1) !== before || check.slice(cE + 1) !== after) {
  throw new Error('FATAL: plugin.js content outside the engine markers changed');
}
console.log('engine block sha256:',
  createHash('sha256').update(nextBlock).digest('hex').slice(0, 12));

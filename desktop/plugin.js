const DEFAULT_ACCENTS = Object.freeze({ signal: '#78BFC2', interpreted: '#B59BCB' });

function getTrack(data, key) {
  const candidate = data && data[key] && typeof data[key] === 'object' ? data[key] : {};
  const fallback = key === 'user' && data && data.dimensions && typeof data.dimensions === 'object'
    ? data.dimensions : {};
  return Object.fromEntries(PORTRAIT_DIMENSIONS.map((d) => {
    const v = candidate[d] ?? (key === 'user' ? fallback[d] : undefined);
    return [d, v == null ? null : clamp01(v)];
  }));
}

function effective(value, confidence, available) {
  const v = value == null ? 0.5 : clamp01(value);
  const c = confidence == null ? (available && value != null ? 0.32 : 0) : clamp01(confidence);
  return { value: v, strength: c, deviation: (v - 0.5) * 2 * c, present: value != null };
}

function channelSet(data) {
  const user = getTrack(data, 'user');
  const agent = getTrack(data, 'agent');
  const confidence = data && data.confidence && typeof data.confidence === 'object' ? data.confidence : {};
  const available = !!(data && data.available);
  const observed = {};
  const interpreted = {};
  for (const d of PORTRAIT_DIMENSIONS) {
    observed[d] = effective(user[d], confidence[d], available);
    interpreted[d] = effective(agent[d], agent[d] == null ? 0 : 0.36, available);
  }
  return { observed, interpreted };
}


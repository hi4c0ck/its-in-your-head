      gazeY: 16.0 + analysis * 0.6 - context * 0.2,
      brow: (directness * 0.42 + exploration * 0.38 + scope * 0.20) * 8.0 - (analysis * 0.66 + directness * 0.18 - exploration * 0.16) * 6.0,

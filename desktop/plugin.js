                  color: 'var(--ui-text-quaternary)', opacity: 0.7,
                  whiteSpace: 'nowrap', overflow: 'hidden', textOverflow: 'ellipsis',
                  pointerEvents: 'none',
                  // contrast pillow (deliberately NOT a bright card): a low
                  // alpha veil of the app surface + backdrop blur so the
                  // ticker stays legible over content; the text-shadow
                  // "cutout glow" in the surface color separates the glyphs
                  // from whatever sits underneath in either theme.
                  background: 'color-mix(in srgb, var(--ui-bg-elevated, transparent) 22%, transparent)',
                  WebkitBackdropFilter: 'blur(3px)',
                  backdropFilter: 'blur(3px)',
                  border: '1px solid color-mix(in srgb, var(--ui-stroke-secondary, transparent) 55%, transparent)',

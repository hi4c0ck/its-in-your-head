/** Render a portrait using a selected registered template. */
function buildPortraitSvg(data = {}, options = {}) {
  const templateId = options.template || DEFAULT_PORTRAIT_TEMPLATE;
  const template = portraitTemplates.get(templateId);
  if (!template) {
    const available = listPortraitTemplates().map((entry) => entry.id).join(', ');
    throw new RangeError(`Unknown portrait template "${templateId}". Available: ${available}`);
  }
  const model = buildPortraitModel(data);
  const renderOptions = {
    ...options,
    template: template.id,
    templateLabel: template.label,
    id: esc(options.id || `iyh-${template.id}`),
  };
  const svg = template.render(model, renderOptions);
  if (typeof svg !== 'string' || !svg.startsWith('<svg')) {
    throw new TypeError(`Portrait template "${template.id}" did not return a complete SVG string`);
  }
  return svg;
}


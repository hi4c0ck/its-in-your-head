const IYH_PORTRAIT_TEMPLATE_PREF_KEY = 'portrait.template.v1'

function createIyhPortraitTemplatePreferences(ctx) {
  const registryIds = () => new Set(
    IYH_PORTRAIT.listPortraitTemplates().map((template) => template.id),
  )
  // Graceful degrade: the plugin-scoped ctx.storage is the persistence door.
  // On an older desktop build without it, fall back to in-memory only so the
  // selector still works (the preference just won't survive a reload).
  const storage = (ctx && typeof ctx.storage === 'object')
    ? ctx.storage
    : { get: (key, fallback) => fallback, set: () => {} }
  const validIds = registryIds()
  const persisted = storage.get(
    IYH_PORTRAIT_TEMPLATE_PREF_KEY,
    IYH_PORTRAIT.DEFAULT_PORTRAIT_TEMPLATE,
  )
  let selected = validIds.has(persisted)
    ? persisted
    : IYH_PORTRAIT.DEFAULT_PORTRAIT_TEMPLATE
  const listeners = new Set()

  return Object.freeze({
    get() {
      return selected
    },
    subscribe(listener) {
      if (typeof listener !== 'function') return () => {}
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    set(templateId) {
      // Re-read the registry so templates registered after store construction
      // are selectable without changing the preference-store implementation.
      if (!registryIds().has(templateId) || selected === templateId) return false
      // Persist first. If storage rejects, do not publish a UI state that will
      // silently disappear on reload.
      storage.set(IYH_PORTRAIT_TEMPLATE_PREF_KEY, templateId)
      selected = templateId
      listeners.forEach((listener) => listener(selected))
      return true
    },
  })
}

// This tiny hook intentionally uses only React APIs already imported by the
